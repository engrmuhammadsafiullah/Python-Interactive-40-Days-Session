phrase = "Python Programming"

# Indexing and Slicing: [start:stop:step]
print(phrase[0])       # 'P' (First character)
print(phrase[-1])      # 'g' (Last character)
print(phrase[0:6])     # 'Python' (Up to, but not including index 6)
print(phrase.upper())  # 'PYTHON PROGRAMMING'
print(phrase.lower())  # 'python programming'
print(len(phrase))     # 18 (Length of the string)

